/* -------------------------------------------------
 * 검사 Variant 생성
 * ------------------------------------------------- */

function createVariants(
  text: string
): string[] {

  const normalized =
    normalizeText(
      text
    );


  const compact =
    makeCompactText(
      normalized
    );


  const collapsed =
    collapseRepeatedCharacters(
      compact
    );


  const compactWithoutAllowed =
    removeAllowedWords(
      compact
    );


  const collapsedWithoutAllowed =
    removeAllowedWords(
      collapsed
    );


  return [
    compactWithoutAllowed,
    collapsedWithoutAllowed,
  ];
}


/* -------------------------------------------------
 * 최종 비속어 검사
 * ------------------------------------------------- */

export function containsProfanity(
  text: string
): boolean {

  if (
    !text ||
    !text.trim()
  ) {
    return false;
  }


  const variants =
    createVariants(
      text
    );


  return variants.some(
    (variant) =>

      BLOCKED_FRAGMENTS.some(
        (blocked) =>

          variant.includes(
            blocked
          )
      )
  );
}